    #[tool(
        description = "List all configured email accounts. Returns {accounts: [{name, email, read_only, allow_move, allow_delete, allow_flag_change}]}. Call first if the user didn't specify an account — every other tool except `account_health` (both cover all accounts) takes an `account` parameter matching the returned name (case-insensitive; optional only when a single account is configured, required otherwise). Inspect `allow_move` / `allow_delete` / `allow_flag_change` before planning write actions instead of trial-and-error."
    )]
    async fn list_accounts(
        &self,
        #[allow(unused)] rmcp::handler::server::wrapper::Parameters(_req): rmcp::handler::server::wrapper::Parameters<ListAccountsRequest>,
    ) -> String {
        let accounts: Vec<serde_json::Value> = self
            .config
            .accounts
            .iter()
            .map(|a| {
                serde_json::json!({
                    "name": a.name,
                    "email": a.sender_address(),
                    "read_only": a.read_only,
                    "allow_move": a.allow_move,
                    "allow_delete": a.allow_delete,
                    "allow_flag_change": a.allow_flag_change,
                })
            })
            .collect();
        serde_json::to_string(&serde_json::json!({ "accounts": accounts }))
            .unwrap_or_else(|e| error_json(&e.to_string()))
    }

    #[tool(
        description = "Report per-account connection health: whether each account currently has a live IMAP session, the last recorded connection error (if any), and OAuth2 token freshness. Use to answer \"why is my Gmail not working?\" without reading server logs. Returns {accounts: [{name, email, auth_method: \"password\" | \"oauth2\", connected: bool, last_error?, oauth_token_valid?, oauth_expires_in_secs?}]} — `oauth_token_valid` / `oauth_expires_in_secs` are set only for OAuth2 accounts. When an OAuth2 refresh fails, `last_error` names the provider's error code (e.g. `invalid_grant` / `AADSTS700082` for a refresh token expired from inactivity) and, when no stored or configured token works any more, the exact `imap-mcp-rs reauth <account>` command the operator has to run — report that verbatim instead of guessing. Purely local — no IMAP roundtrip."
    )]
    async fn account_health(
        &self,
        #[allow(unused)] rmcp::handler::server::wrapper::Parameters(_req): rmcp::handler::server::wrapper::Parameters<AccountHealthRequest>,
    ) -> String {
        let mut accounts = Vec::with_capacity(self.config.accounts.len());
        for account in &self.config.accounts {
            let key = account.name.to_lowercase();
            let state = if let Some(client_arc) = self.clients.get(&key) {
                // Lock each account briefly — the `connection_state`
                // snapshot is pure-read, doesn't touch the network.
                let client = client_arc.lock().await;
                client.connection_state()
            } else {
                // No client registered (shouldn't happen post-construction),
                // treat as disconnected with no prior error.
                crate::imap_client::ConnectionState {
                    connected: false,
                    last_error: None,
                    oauth_token_valid: None,
                    oauth_expires_in_secs: None,
                }
            };
            // `last_error` in the stored state went through `sanitize_log_str`
            // (CR/LF/control) but not through `sanitize_external_str` —
            // re-scrub here so bidi/zero-width in a hostile server's error
            // text can't reach the LLM via this channel. Matches the
            // "every LLM-surface string is sanitize_external_str'd"
            // invariant used elsewhere for subject / filename / etc.
            let safe_last_error = state
                .last_error
                .as_deref()
                .map(crate::email::sanitize_external_str);
            accounts.push(serde_json::json!({
                "name": account.name,
                "email": account.sender_address(),
                "auth_method": match account.auth_method {
                    crate::config::AuthMethod::Password => "password",
                    crate::config::AuthMethod::OAuth2 => "oauth2",
                },
                "connected": state.connected,
                "last_error": safe_last_error,
                "oauth_token_valid": state.oauth_token_valid,
                "oauth_expires_in_secs": state.oauth_expires_in_secs,
            }));
        }
        serde_json::to_string(&serde_json::json!({ "accounts": accounts }))
            .unwrap_or_else(|e| error_json(&e.to_string()))
    }

