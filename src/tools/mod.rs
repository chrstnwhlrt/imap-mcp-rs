/// What every tool returns. `Ok` carries the JSON text of a success, `Err`
/// the `{"error", "retryable"}` object built by [`error_json`]. rmcp turns an
/// `Err` into a tool result flagged `isError: true` — how the MCP
/// specification reports a failed tool execution — with that same JSON text
/// as its content, so a client sees the failure in the flag and the details
/// in the text.
pub type ToolResult = Result<String, String>;

pub fn error_json(msg: &str) -> String {
    let (error, retryable) = error_fields(msg);
    serde_json::to_string(&serde_json::json!({"error": error, "retryable": retryable})).unwrap()
}

/// The `error` and `retryable` of a failure, as [`error_json`] reports
/// them; also what a read over several accounts lists per failed account.
pub(crate) fn error_fields(msg: &str) -> (String, bool) {
    // Strip async-imap's verbose `Option`-debug framing (turns
    // `no response: code: None, info: Some("[NONEXISTENT] ...")`
    // into `Unknown Mailbox: ...`) and scrub any bidi/control chars a
    // hostile server might have smuggled into the response text.
    // No-op for messages that already match our own error format.
    let cleaned = crate::imap_client::clean_imap_error(msg);
    let safe = crate::email::sanitize_external_str(&cleaned);
    // `retryable` is the one bit a caller cannot derive from the text:
    // whether repeating the call later can help. Classified on the RAW
    // message so server framing that `clean_imap_error` strips still
    // counts. Always present — for an unattended caller, `false` is as
    // much of a statement as `true`.
    (safe, crate::imap_client::is_retryable_error(msg))
}

/// The wire name of the folder a call names (see
/// [`ImapClient::resolve_folder`]: the name, its readable form or a role
/// word); the error is the finished tool response.
pub(crate) async fn folder_for(client: &mut ImapClient, requested: &str) -> Result<String, String> {
    let resolved = client.resolve_folder(requested).await;
    resolved.map_err(|e| error_json(&client.check_error(e).to_string()))
}

#[derive(Debug, Clone)]
pub struct ImapMcpServer {
    pub config: ServerConfig,
    pub clients: HashMap<String, Arc<Mutex<ImapClient>>>,
    // Built once in `new` by `Self::tool_router()` (generated by
    // `#[tool_router]`) and dispatched through by the `ServerHandler` impl —
    // `#[tool_handler(router = self.tool_router)]`. The macro's default
    // calls `Self::tool_router()` instead, rebuilding the whole router, every
    // tool's schema included, on each `tools/list` and `tools/call`.
    tool_router: ToolRouter<Self>,
    /// What the handshake sends, built for the configured accounts.
    instructions: String,
}

impl ImapMcpServer {
    /// The server with the tools, schemas and instructions the configured
    /// accounts allow (see `surface.rs`).
    pub fn new(config: ServerConfig, clients: HashMap<String, Arc<Mutex<ImapClient>>>) -> Self {
        let mut tool_router = Self::tool_router();
        surface::apply(&mut tool_router, &config);
        let instructions = surface::instructions(&config);
        Self {
            config,
            clients,
            tool_router,
            instructions,
        }
    }

    /// Resolve an account name to its config and client.
    /// Case-insensitive matching.
    ///
    /// With a single configured account an omitted name falls back to it —
    /// that default is unambiguous. With several accounts it is an ERROR:
    /// the old silent first-account fallback made every call quietly work
    /// in whichever account happened to be listed first, and for `draft_*`
    /// that meant composing from the wrong mailbox under the wrong sender.
    /// A convenience that can misaddress mail loses to one explicit
    /// argument; the error lists the names so recovery is one retry.
    pub fn resolve_client(
        &self,
        account: Option<&str>,
    ) -> Result<(&AccountConfig, Arc<Mutex<ImapClient>>), String> {
        let account = named(account);
        let available = || {
            self.config
                .accounts
                .iter()
                .map(|a| a.name.as_str())
                .collect::<Vec<_>>()
                .join(", ")
        };
        if account.is_none() && self.config.accounts.len() > 1 {
            return Err(format!(
                "Several accounts are configured: pass `account`, the account the email's row \
                 names. Available: {}",
                available()
            ));
        }
        // Must use Unicode-aware `to_lowercase()` (not `eq_ignore_ascii_case`)
        // so accounts named with uppercase non-ASCII chars (e.g. "BÜRO")
        // stay resolvable after the tool-layer lookup lowercases the input.
        // The few per-call allocations here are cheaper than silently
        // breaking a user's config.
        let lookup_name = account.map_or_else(
            || {
                self.config
                    .accounts
                    .first()
                    .map(|a| a.name.to_lowercase())
                    .unwrap_or_default()
            },
            str::to_lowercase,
        );

        let account_config = self
            .config
            .accounts
            .iter()
            .find(|a| a.name.to_lowercase() == lookup_name)
            // The names, like the omitted-account error above: recovery is
            // then one retry instead of a list_accounts round trip.
            .ok_or_else(|| {
                format!(
                    "Account \"{}\" not found. Available: {}",
                    account.unwrap_or_default(),
                    available()
                )
            })?;

        let client = self
            .clients
            .get(&lookup_name)
            .ok_or_else(|| format!("No client for account \"{lookup_name}\""))?
            .clone();

        Ok((account_config, client))
    }

    /// Whether several accounts are configured. Rows then name their
    /// account, and a call on one email has to pass it.
    pub const fn several_accounts(&self) -> bool {
        self.config.accounts.len() > 1
    }

    /// The accounts a read covers: the named one, the only one, or, when
    /// several are configured and the call names none, all of them in the
    /// order of the configuration (see `across.rs`).
    pub fn read_targets(&self, account: Option<&str>) -> Result<Vec<Target<'_>>, String> {
        let account = named(account);
        if account.is_some() || !self.several_accounts() {
            return self.resolve_client(account).map(|target| vec![target]);
        }
        self.config
            .accounts
            .iter()
            .map(|a| self.resolve_client(Some(&a.name)))
            .collect()
    }
}

/// An account and its client, as a read works on them.
pub type Target<'a> = (&'a AccountConfig, Arc<Mutex<ImapClient>>);

/// An optional name as a call gives it, an empty one counting as none: a
/// model fills an optional parameter with `""` rather than leaving it out,
/// and `account: ""` meant an account that does not exist.
pub(crate) fn named(value: Option<&str>) -> Option<&str> {
    value.filter(|v| !v.trim().is_empty())
}

